const WORK24 = JSON.parse(readFileSync(new URL('./parental-leave-work24-cases.json', import.meta.url), 'utf8'));
// 고용24와 다른 것으로 확인한 사례: 나누어떨어지는 일할 금액에서 고용24가 부동소수점 오차로 10원(하한 달은 1원) 적게 나오는 경우
const FLOAT_DIFF = new Set([
  '2026-05-31~2026-07-02', '2028-09-30~2028-12-05', '2027-05-17~2027-11-25', '2027-09-30~2028-07-14',
  '2026-03-28~2026-12-18', '2027-05-31~2028-10-14', '2027-10-15~2028-11-17', '2027-06-27~2027-12-11', '2026-12-28~2027-12-09',
]);
// 30일 시작 → 구간 시작이 윤년 2월 29일로 당겨진 뒤 그 구간을 다 채운 경우: 고용24와 달라 계산 범위 밖(work24-leap)
const LEAP30 = new Set(['2028-01-30~2029-01-13', '2026-12-30~2028-04-29']);

test(`고용24 무작위 대조 ${WORK24.length}건: 차이는 부동소수점 오차뿐, 윤년 2월 29일 패턴은 범위 밖`, () => {
  let same = 0;
  for (const [s, e, w, official] of WORK24) {
    const key = `${s}~${e}`;
    if (LEAP30.has(key)) {
      assert.equal(err(s, e, w), 'work24-leap', key);
      continue;
    }
    const ours = run(s, e, w).total;
    if (FLOAT_DIFF.has(key)) {
      assert.ok(ours - official === 10 || ours - official === 1, `${key} ${ours} ${official}`);
    } else {
      assert.equal(ours, official, `${key} ${w}`);
      same++;
    }
  }
  assert.equal(same, WORK24.length - FLOAT_DIFF.size - LEAP30.size);
});


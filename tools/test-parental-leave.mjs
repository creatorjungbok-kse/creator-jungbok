test('구간 합 = 총액, 일수 합 = 전체 일수(무작위 대조)', () => {
  let seed = 7;
  const rnd = (n) => ((seed = (seed * 1103515245 + 12345) % 2147483648), seed % n);
  for (let k = 0; k < 2000; k++) {
    const s = 20_454 + rnd(1500); // 2026~2030
    const len = rnd(540);
    const from = new Date(s * 86_400_000).toISOString().slice(0, 10);
    const to = new Date((s + len) * 86_400_000).toISOString().slice(0, 10);
    const x = calcLeave({ kind: 'general', start: D(from), end: D(to), wage: 500_000 + rnd(6_000_000), priorMonths: 0, sharedMonths: 0 });
    if (!x.ok) {
      assert.ok(x.error === 'over-18' || x.error === 'work24-leap', x.error);
      continue;
    }
    const r = x.result;
    assert.equal(r.segments.reduce((a, g) => a + g.days, 0), r.totalDays);
    assert.equal(r.segments.reduce((a, g) => a + g.amount, 0), r.total);
    for (const g of r.segments) {
      if (g.monthly > 700_000 || g.full) assert.equal(g.amount % 10, 0);
      if (g.full) assert.equal(g.amount, g.monthly);
      else assert.ok(g.days < g.segDays && g.amount <= Math.ceil((g.monthly * 31) / 28));
    }
  }
});
